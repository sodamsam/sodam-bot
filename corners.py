def _card_prompt(topic, number, extra=""):
    import auto_post as ap
    title, _kw = topic
    return f"""당신은 스레드(Threads) 계정 '소담 AI 랩'의 운영자 '소담쌤'입니다.

{ap.PERSONA}

오늘의 복붙 프롬프트 주제: "{title}"
4장짜리 카드뉴스(표지 → 복사할 문장 → 결과 예시 → 팁)와, 함께 올릴 짧은 글머리를 만듭니다.

{ap._PROMPT_QUALITY_RULES}

[출력 형식 — 아래 마커를 정확히 그대로 사용]
[카드제목]
(표지 큰 글씨. 24자 이내. "무엇이 해결되는지"가 바로 보이게. 예: "회의록 정리, 이 문장 하나로 끝나요")
[상황]
(독자가 겪는 불편 한 줄. 30자 이내)
[프롬프트]
(그대로 복사해 쓰는 완성형 프롬프트. 6줄 이내, 바꿔 넣을 자리는 [대괄호]로, 출력 형식 지정, 마지막에 "없는 내용은 지어내지 마")
[결과예시]
(이 프롬프트를 쓰면 나오는 결과의 짧은 예시. 3줄 이내, 담백하게)
[팁]
(더 잘 쓰는 법 한 가지. 50자 이내)
[후킹]
(스레드 글 첫 줄. 25자 이내, 배경 설명 없이 상황이나 결과부터)

[어조 규칙]
- 부드러운 존댓말, 과장·어그로·통계 금지, 전문용어 금지, 이모지 사용 금지
- 지어낸 경험담 금지
{extra}"""


_CARD_MARKERS = ("카드제목", "상황", "프롬프트", "결과예시", "팁", "후킹")


def _gen_card(topic, number, extra=""):
    """프롬프트 카드 초안. 형식이 깨지면 None."""
    import auto_post as ap
    raw = ap._call_gemini(_card_prompt(topic, number, extra), max_tokens=1000)
    parts = ap._split_markers(raw, _CARD_MARKERS)
    got = {k: parts[k].strip() for k in _CARD_MARKERS}
    if not all(got[k] for k in ("카드제목", "프롬프트", "결과예시", "후킹")):
        print(f"[저녁 코너] 카드 초안 형식 불량: 비어 있는 항목 {[k for k in _CARD_MARKERS if not got[k]]}")
        return None
    if "[" not in got["프롬프트"] or "]" not in got["프롬프트"]:
        print("[저녁 코너] 프롬프트에 [바꿔 넣을 자리]가 없어 다시 만듭니다")
        return None
    got["카드제목"] = got["카드제목"].splitlines()[0].strip()[:40]
    got["후킹"] = got["후킹"].splitlines()[0].strip()
    return got


def _card_body(label, got):
    """스레드 본문. 500자 한도 안에서 프롬프트가 잘리지 않게 후킹 → 안내 순으로 줄인다."""
    import auto_post as ap
    closing = random.choice(CARD_CLOSINGS)
    prompt = got["프롬프트"].strip()
    hook = ap.wrap_lines(got["후킹"], limit=20)
    for parts in ([label, hook, prompt, closing], [label, prompt, closing]):
        body = "\n\n".join(parts)
        if len(body) <= 490:
            return body
    return "\n\n".join([label, hook, "복사할 문장은 카드 2번째 장에 있어요", closing])[:490]


def write_evening_post(state, now_kst, forced=None):
    """저녁 코너 글을 만든다. 실패하면 None (호출부에서 검증된 기존 글로 대체).

    반환: {"kind", "text", "tag", "topic", "number", "card": 카드 데이터 또는 None}
    """
    import auto_post as ap
    import prompt_queue

    kind = pick_kind(now_kst, forced)
    cfg = CORNERS[kind]
    seq = (state.get("corner_seq") or {}).get(kind, 0)
    number = seq + 1
    label = f"{cfg['emoji']} {cfg['label']} #{number}"

    if kind == "card_prompt":
        topics = prompt_queue.ordered_topics(ap.PROMPT_BANK, ap.AREAS)
        t = topics[-1 - (seq % len(topics))]          # 아침 큐와 겹치지 않도록 뒤에서부터
        topic = (t["topic"], t["keyword"])
        got = None
        for attempt in range(2):
            extra = "" if attempt == 0 else "\n[경고] 직전 시도의 형식이 틀렸습니다. 마커를 정확히 지키고 [프롬프트]에 [대괄호] 자리를 꼭 넣으세요."
            got = _gen_card(topic, number, extra)
            if got:
                problems = find_problems(" ".join([got["카드제목"], got["상황"], got["팁"], got["후킹"]]))
                if not problems:
                    break
                print(f"[저녁 코너] 근거 없는 표현 발견 {problems}")
                got = None
        if not got:
            return None
        card = {"series": f"{cfg['label']} #{number}", "headline": got["카드제목"], "situation": got["상황"],
                "prompt": got["프롬프트"], "example": got["결과예시"],
                "tip": got["팁"] or "결과가 마음에 안 들면 \"더 짧게\"처럼 한 번 더 부탁해 보세요."}
        return {"kind": kind, "text": _card_body(label, got), "tag": cfg["tag"],
                "topic": topic[0], "number": number, "card": card}

    bank = {"term": TERMS, "mistake": MISTAKES, "tip": TIPS, "engage": ENGAGE_TOPICS}[kind]
    topic = bank[seq % len(bank)]
    title = topic if isinstance(topic, str) else topic[0]
    text = None
    for attempt in range(2):
        extra = "" if attempt == 0 else f"\n[경고] 직전 시도에 근거 없는 표현이 있었습니다: {problems}. 숫자·통계·인용·경험담 없이 다시 쓰세요."
        candidate, raw_body = _gen_text(kind, topic, number, extra)
        problems = find_problems(raw_body)  # 머리글의 "#12"가 해시태그로 오인되지 않게 본문만 검사
        if not problems:
            text = candidate
            break
        print(f"[저녁 코너] {kind} 근거 없는 표현 발견 {problems}")
    if not text:
        return None
    return {"kind": kind, "text": text, "tag": cfg["tag"], "topic": title, "number": number, "card": None}
