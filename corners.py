def find_problems(text):
    """통계·연구 인용·지어낸 경험담처럼 근거를 확인할 수 없는 표현을 찾는다."""
    import auto_post as ap
    problems = [m.group() for m in ap.CLAIM_PATTERN.finditer(text)]
    problems += [p for p in _BANNED_PHRASES if p in text]
    if re.search(r"https?://|www\.|#\S", text):
        problems.append("링크·해시태그")
    return problems


